import { execFileSync } from "node:child_process";
import {
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { codexCompatibility } from "../src/codex/codex-compatibility.mjs";

const packageRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const defaultGeneratedRoot = path.join(
  packageRoot,
  "src/codex/generated/codex-app-server",
);
const manifestRelativePath = "THREAD_ITEM_GENERATION.json";

function readCodexVersion() {
  const output = execFileSync("codex", ["--version"], {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "inherit"],
  }).trim();
  const actualVersion = output.match(
    /(\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?)$/,
  )?.[1];

  if (!actualVersion) {
    throw new Error(`Could not parse the Codex version from: ${output}`);
  }
  if (actualVersion !== codexCompatibility.schemaGenerationVersion) {
    throw new Error(
      `Codex contract generation requires ${codexCompatibility.schemaGenerationVersion}, but the active CLI is ${actualVersion}`,
    );
  }

  return actualVersion;
}

function provenanceHeader(version) {
  return `// Generated from Codex ${version}.\n`;
}

function writeThreadItemTypeClosure(typescriptDirectory, stagedRoot, version) {
  const pending = ["v2/ThreadItem.ts"];
  const visited = new Set();

  while (pending.length > 0) {
    const relativePath = pending.pop();
    if (!relativePath || visited.has(relativePath)) {
      continue;
    }
    visited.add(relativePath);

    const sourcePath = path.join(typescriptDirectory, relativePath);
    const source = readFileSync(sourcePath, "utf8");
    const sourceDirectory = path.dirname(relativePath);
    for (const match of source.matchAll(/from "([^"]+)"/g)) {
      pending.push(
        path.normalize(path.join(sourceDirectory, `${match[1]}.ts`)),
      );
    }

    const nodeNextSource = source.replace(
      /from "([^"]+)"/g,
      (_match, importPath) => `from "${importPath}.js"`,
    );
    const stampedSource = nodeNextSource.startsWith(
      "// GENERATED CODE! DO NOT MODIFY BY HAND!\n",
    )
      ? nodeNextSource.replace(
          "// GENERATED CODE! DO NOT MODIFY BY HAND!\n",
          `// GENERATED CODE! DO NOT MODIFY BY HAND!\n${provenanceHeader(version)}`,
        )
      : `${provenanceHeader(version)}${nodeNextSource}`;
    const outputPath = path.join(stagedRoot, "schema", relativePath);
    mkdirSync(path.dirname(outputPath), { recursive: true });
    writeFileSync(outputPath, stampedSource);
  }

  return [...visited]
    .sort()
    .map((relativePath) => path.join("schema", relativePath));
}

function writeThreadItemRuntimeSchema(
  jsonSchemaDirectory,
  stagedRoot,
  version,
) {
  const notificationSchemaPath = path.join(
    jsonSchemaDirectory,
    "v2/ItemCompletedNotification.json",
  );
  const notificationSchema = JSON.parse(
    readFileSync(notificationSchemaPath, "utf8"),
  );

  if (!notificationSchema.definitions?.ThreadItem) {
    throw new Error(
      "Codex ItemCompletedNotification schema does not define ThreadItem",
    );
  }

  const threadItemSchema = {
    $schema: notificationSchema.$schema,
    $ref: "#/definitions/ThreadItem",
    definitions: notificationSchema.definitions,
  };
  const source = `// GENERATED CODE! DO NOT MODIFY BY HAND!\n${provenanceHeader(version)}// Generated by scripts/generate-codex-contracts.mjs from the official Codex app-server schema.\n\nexport const codexThreadItemJsonSchema = ${JSON.stringify(threadItemSchema, null, 2)} as const;\n`;
  const relativePath = "runtime/ThreadItem.schema.ts";
  const outputPath = path.join(stagedRoot, relativePath);

  mkdirSync(path.dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, source);
  return relativePath;
}

function writeReadme(stagedRoot, generatedRoot, version) {
  const readmePath = path.join(generatedRoot, "README.md");
  const marker = `<!-- codex-contract-provenance: schema-generation-version=${version} -->`;
  let source;
  try {
    source = readFileSync(readmePath, "utf8").replace(
      /\n*<!-- codex-contract-provenance: schema-generation-version=[^ ]+ -->\n*/,
      "\n",
    );
  } catch (error) {
    if (error?.code !== "ENOENT") {
      throw error;
    }
    source = "# Codex App-Server Type Generation\n";
  }

  const headingEnd = source.indexOf("\n") + 1;
  const body = source.slice(headingEnd).replace(/^\n*/, "");
  const stampedSource = `${source.slice(0, headingEnd)}\n${marker}\n\n${body}`;
  writeFileSync(path.join(stagedRoot, "README.md"), stampedSource);
}

function readPreviousManagedFiles(generatedRoot) {
  try {
    const manifest = JSON.parse(
      readFileSync(path.join(generatedRoot, manifestRelativePath), "utf8"),
    );
    return Array.isArray(manifest.generatedFiles)
      ? manifest.generatedFiles.filter((value) => typeof value === "string")
      : [];
  } catch (error) {
    if (error?.code === "ENOENT") {
      return [];
    }
    throw error;
  }
}

function listStagedFiles(root, relativeDirectory = "") {
  const directory = path.join(root, relativeDirectory);
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const relativePath = path.join(relativeDirectory, entry.name);
    return entry.isDirectory()
      ? listStagedFiles(root, relativePath)
      : [relativePath];
  });
}

function reconcileGeneratedFiles(stagedRoot, generatedRoot, managedFiles) {
  const previousManagedFiles = readPreviousManagedFiles(generatedRoot);
  const stagedFiles = listStagedFiles(stagedRoot);

  mkdirSync(generatedRoot, { recursive: true });
  for (const relativePath of stagedFiles) {
    const targetPath = path.join(generatedRoot, relativePath);
    const temporaryTargetPath = `${targetPath}.next-${process.pid}`;
    mkdirSync(path.dirname(targetPath), { recursive: true });
    writeFileSync(
      temporaryTargetPath,
      readFileSync(path.join(stagedRoot, relativePath)),
    );
    renameSync(temporaryTargetPath, targetPath);
  }

  const currentManagedFiles = new Set(managedFiles);
  for (const relativePath of previousManagedFiles) {
    if (!currentManagedFiles.has(relativePath)) {
      rmSync(path.join(generatedRoot, relativePath), { force: true });
    }
  }
}

export function generateCodexContracts({
  generatedRoot = process.env.BB_CODEX_CONTRACTS_OUTPUT_ROOT
    ? path.resolve(process.env.BB_CODEX_CONTRACTS_OUTPUT_ROOT)
    : defaultGeneratedRoot,
} = {}) {
  // Verify provenance before creating any temporary or committed output.
  const version = readCodexVersion();
  const temporaryDirectory = mkdtempSync(
    path.join(tmpdir(), "bb-codex-contracts-"),
  );

  try {
    const typescriptDirectory = path.join(temporaryDirectory, "typescript");
    const jsonSchemaDirectory = path.join(temporaryDirectory, "json-schema");
    const stagedRoot = path.join(temporaryDirectory, "staged");
    execFileSync(
      "codex",
      ["app-server", "generate-ts", "--out", typescriptDirectory],
      { stdio: "inherit" },
    );
    execFileSync(
      "codex",
      ["app-server", "generate-json-schema", "--out", jsonSchemaDirectory],
      { stdio: "inherit" },
    );

    const typeFiles = writeThreadItemTypeClosure(
      typescriptDirectory,
      stagedRoot,
      version,
    );
    const runtimeSchema = writeThreadItemRuntimeSchema(
      jsonSchemaDirectory,
      stagedRoot,
      version,
    );
    const managedFiles = [...typeFiles, runtimeSchema].sort();
    writeReadme(stagedRoot, generatedRoot, version);
    writeFileSync(
      path.join(stagedRoot, manifestRelativePath),
      `${JSON.stringify(
        {
          schemaGenerationVersion: version,
          generatedFiles: managedFiles,
        },
        null,
        2,
      )}\n`,
    );

    reconcileGeneratedFiles(stagedRoot, generatedRoot, managedFiles);
    console.log(
      `Wrote ${typeFiles.length} ThreadItem type files and its runtime schema from Codex ${version}`,
    );
  } finally {
    rmSync(temporaryDirectory, { recursive: true, force: true });
  }
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  generateCodexContracts();
}
