function outputFileName(file, color) {
  return file.replace(/\.png$/u, `-${color}.png`);
}

function composedAppIconSvg({
  background,
  logoWidth = 320,
  rounded = true,
  tint,
}) {
  const logoHeight = (logoWidth * 405) / 507;
  const logoX = (512 - logoWidth) / 2;
  const logoY = (512 - logoHeight) / 2;
  const tile = rounded
    ? `<rect x="43" y="43" width="426" height="426" rx="104" fill="${background}"/>`
    : `<rect width="512" height="512" fill="${background}"/>`;

  return Buffer.from(
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">${tile}<svg x="${logoX}" y="${logoY}" width="${logoWidth}" height="${logoHeight}" viewBox="-8 -8 507 405">${appIconLogoContents(tint)}</svg></svg>`,
  );
}

async function renderSquare(svg, size) {
  // Rasterize the vector at 2x its 512-unit design canvas (or at the target
  // size for 1024px desktop assets), then downsample once. This keeps curves
  // and subpixel rim strokes crisp instead of enlarging a 512px intermediate.
  return sharp(svg, { density: 144 })
    .resize({
      width: size,
      height: size,
      fit: "contain",
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    })
    .png()
    .toBuffer();
}

async function renderSolidMark(size, fill) {
  const source = Buffer.from(
    markSvg.toString("utf8").replace('fill="#111"', `fill="${fill}"`),
  );
  return renderSquare(source, size);
}

async function monochromePng(source) {
  const { data, info } = await sharp(source)
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  const output = Buffer.from(data);
  for (let index = 0; index < output.length; index += 4) {
    const luma =
      0.2126 * data[index] +
      0.7152 * data[index + 1] +
      0.0722 * data[index + 2];
    const maskAlpha =
      luma >= 245
        ? 0
        : Math.round(
            255 * Math.sqrt((245 - luma) / 245) * (data[index + 3] / 255),
          );
    output[index] = 255;
    output[index + 1] = 255;
    output[index + 2] = 255;
    output[index + 3] = maskAlpha;
  }
  return sharp(output, {
    raw: { width: info.width, height: info.height, channels: 4 },
  })
    .png()
    .toBuffer();
}

function generatedManifest(baseManifest, color) {
  return Buffer.from(
    `${JSON.stringify(
      {
        ...baseManifest,
        icons: baseManifest.icons.map((icon) =>
          icon.purpose === "monochrome"
            ? icon
            : {
                ...icon,
                src: icon.src.replace(
                  /\.(png|svg)$/u,
                  (_extension, format) => `-${color}.${format}`,
                ),
              },
        ),
      },
      null,
      2,
    )}\n`,
  );
}

async function writeOrCheck(filePath, content) {
  let existing = null;
  try {
    existing = await readFile(filePath);
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }

  if (existing?.equals(content)) return;
  if (
    checkOnly &&
    existing &&
    extname(filePath) === ".png" &&
    (await pngsVisuallyEquivalent(existing, content))
  ) {
    return;
  }
  if (checkOnly) {
    mismatches.push(relative(projectRoot, filePath));
    return;
  }

  await mkdir(dirname(filePath), { recursive: true });
  await writeFile(filePath, content);
  writes += 1;
}

async function pngsVisuallyEquivalent(existing, generated) {
  const [existingImage, generatedImage] = await Promise.all([
    sharp(existing).ensureAlpha().raw().toBuffer({ resolveWithObject: true }),
    sharp(generated).ensureAlpha().raw().toBuffer({ resolveWithObject: true }),
  ]);

  if (
    existingImage.info.width !== generatedImage.info.width ||
    existingImage.info.height !== generatedImage.info.height ||
    existingImage.info.channels !== generatedImage.info.channels
  ) {
    return false;
  }

  let differingChannels = 0;
  for (let index = 0; index < existingImage.data.length; index += 1) {
    const delta = Math.abs(
      existingImage.data[index] - generatedImage.data[index],
    );
    if (delta === 0) continue;
    if (delta > maxPngChannelDelta) return false;
    differingChannels += 1;
    if (differingChannels > maxPngDifferingChannels) return false;
  }

  return true;
}

async function generateIcns(sourcePng) {
  const temporaryDirectory = await mkdtemp(join(tmpdir(), "bb-icon-"));
  const iconsetDirectory = join(temporaryDirectory, "bb.iconset");
  const outputPath = join(temporaryDirectory, "bb.icns");
  await mkdir(iconsetDirectory);

  try {
    const sizes = [16, 32, 128, 256, 512];
    await Promise.all(
      sizes.flatMap((size) => [
        sharp(sourcePng)
          .resize(size, size)
          .png()
          .toFile(join(iconsetDirectory, `icon_${size}x${size}.png`)),
        sharp(sourcePng)
          .resize(size * 2, size * 2)
          .png()
          .toFile(join(iconsetDirectory, `icon_${size}x${size}@2x.png`)),
      ]),
    );
    await execFileAsync("iconutil", [
      "-c",
      "icns",
      "-o",
      outputPath,
      iconsetDirectory,
    ]);
    return await readFile(outputPath);
  } finally {
    await rm(temporaryDirectory, { recursive: true, force: true });
  }
}

