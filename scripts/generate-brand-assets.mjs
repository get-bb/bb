// Sharp/libvips can round a handful of SVG-filter pixels one channel value
// differently on arm64 and x64. Keep this tolerance deliberately tiny: it
// accepts the architecture-only variance while still rejecting any visible or
// widespread change to a generated PNG.
const maxPngChannelDelta = 1;
const maxPngDifferingChannels = 64;

function generatedConnectIconModule() {
  const compactSvg = markSvg
    .toString("utf8")
    .replace(/ role="img" aria-labelledby="title desc"/u, "")
    .replace(/\s*<title[\s\S]*?<\/title>/u, "")
    .replace(/\s*<desc[\s\S]*?<\/desc>/u, "")
    .replace(/>\s+</gu, "><")
    .trim();
  return Buffer.from(
    `// Generated by scripts/generate-brand-assets.mjs from assets/bb-mark.svg.\nconst BB_MARK_SVG = ${JSON.stringify(compactSvg)};\n\nexport const BB_ICON_DATA_URI = \`data:image/svg+xml,\${encodeURIComponent(BB_MARK_SVG)}\`;\n`,
  );
}

function parseHex(hex) {
  return [1, 3, 5].map((index) =>
    Number.parseInt(hex.slice(index, index + 2), 16),
  );
}

function mixHex(from, to, amount) {
  const fromRgb = parseHex(from);
  const toRgb = parseHex(to);
  return `#${fromRgb
    .map((channel, index) =>
      Math.round(channel + (toRgb[index] - channel) * amount)
        .toString(16)
        .padStart(2, "0"),
    )
    .join("")}`;
}

function tintedSurfaces(tint) {
  return {
    background: [
      mixHex(tint, "#ffffff", 0.18),
      mixHex(tint, "#ffffff", 0.07),
      tint,
      mixHex(tint, "#000000", 0.04),
      mixHex(tint, "#000000", 0.09),
    ],
    foreground: [
      mixHex(tint, "#ffffff", 0.24),
      mixHex(tint, "#ffffff", 0.1),
      mixHex(tint, "#ffffff", 0.02),
      mixHex(tint, "#000000", 0.02),
      mixHex(tint, "#000000", 0.07),
    ],
  };
}

function replaceGradientStops(contents, gradientId, colors) {
  const gradientPattern = new RegExp(
    `(<linearGradient id="${gradientId}"[\\s\\S]*?<\\/linearGradient>)`,
    "u",
  );
  let replacedStops = 0;
  const result = contents.replace(gradientPattern, (gradient) =>
    gradient.replace(/stop-color="#[0-9a-f]+"/giu, () => {
      const color = colors[replacedStops];
      replacedStops += 1;
      return `stop-color="${color}"`;
    }),
  );
  if (replacedStops !== colors.length) {
    throw new Error(
      `Expected ${colors.length} stops in ${gradientId}, found ${replacedStops}`,
    );
  }
  return result;
}

