function generatedConnectIconModule() {
  const compactSvg = markSvg
    .toString("utf8")
    .replace(/ role="img" aria-labelledby="title desc"/u, "")
    .replace(/\s*<title[\s\S]*?<\/title>/u, "")
    .replace(/\s*<desc[\s\S]*?<\/desc>/u, "")
    .replace(/>\s+</gu, "><")
    .trim();
  return Buffer.from(
    `// Generated by scripts/generate-brand-assets.mjs from assets/bb-mark.svg.\nconst BB_MARK_SVG = ${JSON.stringify(compactSvg)};\n\nexport const BB_ICON_DATA_URI = \`data:image/svg+xml,\${encodeURIComponent(BB_MARK_SVG)}\`;\n`,
  );
}

function parseHex(hex) {
  return [1, 3, 5].map((index) =>
    Number.parseInt(hex.slice(index, index + 2), 16),
  );
}

function outputFileName(file, color) {
  return file.replace(/\.png$/u, `-${color}.png`);
}

function composedAppIconSvg({ background, logoWidth = 320, rounded = true }) {
  const logoHeight = (logoWidth * 405) / 507;
  const logoX = (512 - logoWidth) / 2;
  const logoY = (512 - logoHeight) / 2;
  const tile = rounded
    ? `<rect x="43" y="43" width="426" height="426" rx="104" fill="${background}"/>`
    : `<rect width="512" height="512" fill="${background}"/>`;

  return Buffer.from(
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">${tile}<svg x="${logoX}" y="${logoY}" width="${logoWidth}" height="${logoHeight}" viewBox="-8 -8 507 405">${appIconLogoContents}</svg></svg>`,
  );
}

async function renderSquare(svg, size) {
  return sharp(svg)
    .resize({
      width: size,
      height: size,
      fit: "contain",
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    })
    .png()
    .toBuffer();
}

async function renderSolidMark(size, fill) {
  const source = Buffer.from(
    markSvg.toString("utf8").replace('fill="#111"', `fill="${fill}"`),
  );
  return renderSquare(source, size);
}

function tintTileIcon(data, colorRgb) {
  const output = Buffer.from(data);
  for (let index = 0; index < output.length; index += 4) {
    const red = data[index];
    const green = data[index + 1];
    const blue = data[index + 2];
    const alpha = data[index + 3];
    if (alpha === 0) continue;

    const luma = 0.2126 * red + 0.7152 * green + 0.0722 * blue;
    if (luma >= 245) continue;

    // Keep the darkest parts close to the selected color while allowing the
    // vector lighting to open into a real highlight. The old square icons had
    // this wider tonal range; a square-root mask compressed the new mark into
    // an almost flat mid-tone after tinting.
    const maskAlpha = Math.round(
      255 * (1 - Math.pow(luma / 245, 1.7)) * (alpha / 255),
    );
    if (maskAlpha <= 0) continue;

    const ratio = maskAlpha / 255;
    output[index] = Math.round(colorRgb[0] * ratio + 255 * (1 - ratio));
    output[index + 1] = Math.round(colorRgb[1] * ratio + 255 * (1 - ratio));
    output[index + 2] = Math.round(colorRgb[2] * ratio + 255 * (1 - ratio));
    output[index + 3] = alpha;
  }
  return output;
}

async function tintedPng(source, hex) {
  const { data, info } = await sharp(source)
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  const output = tintTileIcon(data, parseHex(hex));

  return sharp(output, {
    raw: { width: info.width, height: info.height, channels: 4 },
  })
    .png()
    .toBuffer();
}

async function monochromePng(source) {
  const { data, info } = await sharp(source)
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  const output = Buffer.from(data);
  for (let index = 0; index < output.length; index += 4) {
    const luma =
      0.2126 * data[index] +
      0.7152 * data[index + 1] +
      0.0722 * data[index + 2];
    const maskAlpha =
      luma >= 245
        ? 0
        : Math.round(
            255 * Math.sqrt((245 - luma) / 245) * (data[index + 3] / 255),
          );
    output[index] = 255;
    output[index + 1] = 255;
    output[index + 2] = 255;
    output[index + 3] = maskAlpha;
  }
  return sharp(output, {
    raw: { width: info.width, height: info.height, channels: 4 },
  })
    .png()
    .toBuffer();
}

function generatedManifest(baseManifest, color) {
  return Buffer.from(
    `${JSON.stringify(
      {
        ...baseManifest,
        icons: baseManifest.icons.map((icon) =>
          icon.purpose === "monochrome"
            ? icon
            : {
                ...icon,
                src: icon.src.replace(/\.png$/u, `-${color}.png`),
              },
        ),
      },
      null,
      2,
    )}\n`,
  );
}

async function writeOrCheck(filePath, content) {
  let existing = null;
  try {
    existing = await readFile(filePath);
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }

  if (existing?.equals(content)) return;
  if (checkOnly) {
    mismatches.push(relative(projectRoot, filePath));
    return;
  }

  await mkdir(dirname(filePath), { recursive: true });
  await writeFile(filePath, content);
  writes += 1;
}

async function generateIcns(sourcePng) {
  const temporaryDirectory = await mkdtemp(join(tmpdir(), "bb-icon-"));
  const iconsetDirectory = join(temporaryDirectory, "bb.iconset");
  const outputPath = join(temporaryDirectory, "bb.icns");
  await mkdir(iconsetDirectory);

  try {
    const sizes = [16, 32, 128, 256, 512];
    await Promise.all(
      sizes.flatMap((size) => [
        sharp(sourcePng)
          .resize(size, size)
          .png()
          .toFile(join(iconsetDirectory, `icon_${size}x${size}.png`)),
        sharp(sourcePng)
          .resize(size * 2, size * 2)
          .png()
          .toFile(join(iconsetDirectory, `icon_${size}x${size}@2x.png`)),
      ]),
    );
    await execFileAsync("iconutil", [
      "-c",
      "icns",
      "-o",
      outputPath,
      iconsetDirectory,
    ]);
    return await readFile(outputPath);
  } finally {
    await rm(temporaryDirectory, { recursive: true, force: true });
  }
}

